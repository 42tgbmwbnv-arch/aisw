st.title("🍽️ Streamlit + OpenAI Vision 칼로리 계산기")

uploaded = st.file_uploader("📷 음식 사진 업로드", type=["jpg", "jpeg", "png"])
manual_name = st.text_input("🍜 음식 이름 직접 입력 (선택)")
grams = st.number_input("⚖️ 그램 입력", min_value=1.0, max_value=3000.0, value=100.0)
btn = st.button("예측하기")

if btn:
    if not uploaded:
        st.error("사진을 업로드하세요.")
        st.stop()

    img = Image.open(uploaded).convert("RGB")
    st.image(img, use_column_width=True, caption="업로드된 이미지")

    # 음식 이름 우선순위: 직접 입력 > Vision 예측
    if manual_name.strip():
        candidates = [manual_name.strip()]
    else:
        st.info("🔍 OpenAI Vision으로 음식 이름 예측 중…")
        candidates = predict_food_names(img)
        st.write("📌 Vision 예측:", candidates)

    # Nutrition lookup
    found = None
    final_name = None

    for name in candidates:
        entry = ensure_nutrition_entry(name)
        if entry:
            found = entry
            final_name = name
            break

    if not found:
        st.error("❌ 어떤 음식에서도 영양정보를 찾을 수 없습니다.")
        st.stop()

    # 계산
    result = calculate_nutrition(found, grams)

    # 출력
    st.subheader(f"🍜 최종 음식: {final_name}")
    st.markdown(f"""
    ### 📊 영양 분석
    - 칼로리: **{result['kcal']} kcal**
    - 탄수화물: {result['carbs_g']}
    - 단백질: {result['protein_g']}
    - 지방: {result['fat_g']}
    - 사용 그램: {result['grams']} g
    """)

    st.success("완료 🎉")