# 8) 칼로리 계산
# =========================================================
def calculate_nutrition(entry, grams):
    factor = grams / 100.0
    return {
        "kcal": round(entry.get("kcal", 0) * factor, 1),
        "carbs_g": entry.get("carbs_g"),
        "protein_g": entry.get("protein_g"),
        "fat_g": entry.get("fat_g"),
        "grams": grams
    }


