# 6) 영양 정보 확보
# =========================================================
def ensure_nutrition_entry(food_name: str):
    db = load_db()
    key = food_name.lower()

    if key in db and db[key].get("kcal"):
        return db[key]

    # OpenFoodFacts
    off = off_search(food_name)
    if off:
        db[key] = off
        save_db(db)
        return off

    # Safe scrape
    web = safe_scrape(food_name)
    if web:
        db[key] = web
        save_db(db)
        return web

    return None


